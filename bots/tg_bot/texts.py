def get_employee_menu_text(role: str, full_name: str) -> str:
    """
    Generate role-specific employee menu text.
    
    Args:
        role: Staff role (manager, technical_support, duty_engineer, administrator)
        full_name: Employee full name
    
    Returns:
        Formatted menu text with role-specific information
    """
    role_info = {
        "manager": {
            "emoji": "👨‍💼",
            "title": "Менеджер",
            "description": "Управление заявками и клиентами"
        },
        "technical_support": {
            "emoji": "🛠",
            "title": "Техническая поддержка",
            "description": "Обработка технических обращений"
        },
        "duty_engineer": {
            "emoji": "⚙️",
            "title": "Дежурный инженер",
            "description": "Оперативная поддержка"
        },
        "administrator": {
            "emoji": "👑",
            "title": "Администратор",
            "description": "Полный доступ к системе и админ-панели"
        }
    }
    
    info = role_info.get(role, role_info["manager"])
    
    text = f"{info['emoji']} Меню сотрудника\n\n"
    text += f"Роль: {info['title']}\n"
    text += f"{info['description']}\n\n"
    
    if role == "administrator":
        text += "✨ Доступна админ-панель для управления системой\n\n"
    
    text += "Выберите действие:"
    
    return text


